def _rgb_to_hsl(r, g, b):
    r, g, b = r / 255, g / 255, b / 255
    mx, mn = max(r, g, b), min(r, g, b)
    l = (mx + mn) / 2
    if mx == mn:
        return 0.0, 0.0, l
    d = mx - mn
    s = d / (2 - mx - mn) if l > 0.5 else d / (mx + mn)
    if mx == r:
        h = (g - b) / d + (6 if g < b else 0)
    elif mx == g:
        h = (b - r) / d + 2
    else:
        h = (r - g) / d + 4
    return h / 6, s, l


def _hsl(color) -> tuple:
    """(h 0..1, s, l) of a colour (str / QColor / (h, s, l) passes through)."""
    if isinstance(color, tuple):
        return color
    c = QColor(color)
    return _rgb_to_hsl(c.red(), c.green(), c.blue())


def _clamp01(v):
    return 0.0 if v < 0 else 1.0 if v > 1 else v


def _shade(color, dl, ds=0.0) -> tuple:
    """shade(): lightness by dl, saturation by ds; darker gets a touch richer."""
    h, s, l = _hsl(color)
    return h, _clamp01(s + ds + (-dl * 0.25 if dl < 0 else 0)), _clamp01(l + dl)


def _mix(a, b, t) -> tuple:
    """mixCss(): interpolate the hsl numbers (hue linearly, as the source)."""
    return tuple(x + (y - x) * t for x, y in zip(a, b))


def _qcolor(hsl, alpha=1.0) -> QColor:
    return QColor.fromHslF(hsl[0] % 1.0, _clamp01(hsl[1]), _clamp01(hsl[2]), alpha)


def _luminance(c: QColor) -> float:
    def lin(v):
        x = v / 255
        return x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4
    return 0.2126 * lin(c.red()) + 0.7152 * lin(c.green()) + 0.0722 * lin(c.blue())


