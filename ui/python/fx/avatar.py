_path_cache: dict = {}


def shape_path(shape: str) -> QPainterPath:
    """The body outline in the source's 100 x 100 design box (centre 50,50),
    filled with Qt.WindingFill. ValueError for an unknown shape."""
    if shape not in _path_cache:
        if shape in _BUILT:
            _path_cache[shape] = _BUILT[shape]()
        elif shape in _SVG_PATHS:
            _path_cache[shape] = _svg_path(_SVG_PATHS[shape])
        else:
            raise ValueError(f"unknown avatar shape {shape!r}; one of {', '.join(SHAPES)}")
    return QPainterPath(_path_cache[shape])


def _parts_path(shape: str):
    """The thin parts (antennae) of a shape, or None."""
    key = shape + ":parts"
    if key not in _path_cache:
        _path_cache[key] = _svg_path(_SVG_PARTS[shape]) if shape in _SVG_PARTS else None
    return _path_cache[key]


