_TOKEN = re.compile(r"[MLHVCQAZ]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def _arc_to(path: QPainterPath, x1, y1, r, large, sweep, x2, y2):
    """An SVG endpoint arc (circular, unrotated) onto a QPainterPath."""
    hx, hy = (x1 - x2) / 2, (y1 - y2) / 2
    d2 = hx * hx + hy * hy
    if d2 == 0:
        return
    r = max(r, math.sqrt(d2))
    coef = math.sqrt(max(0.0, (r * r - d2) / d2))
    if large == sweep:
        coef = -coef
    cx = coef * hy + (x1 + x2) / 2
    cy = coef * -hx + (y1 + y2) / 2
    a0 = math.atan2(y1 - cy, x1 - cx)
    a1 = math.atan2(y2 - cy, x2 - cx)
    da = a1 - a0
    if sweep and da < 0:
        da += 2 * math.pi
    elif not sweep and da > 0:
        da -= 2 * math.pi
    # Qt's angles run counter-clockwise on screen (y down): negate.
    path.arcTo(QRectF(cx - r, cy - r, 2 * r, 2 * r), -math.degrees(a0), -math.degrees(da))


def _svg_path(d: str) -> QPainterPath:
    """Absolute M L H V C Q A Z, as gen-shapes.mjs writes them."""
    path = QPainterPath()
    path.setFillRule(Qt.WindingFill)
    toks = _TOKEN.findall(d)
    i, cmd = 0, None
    x = y = sx = sy = 0.0

    def num():
        nonlocal i
        i += 1
        return float(toks[i - 1])

    while i < len(toks):
        if toks[i].isalpha():
            cmd = toks[i]
            i += 1
        if cmd == "M":
            x, y = num(), num()
            sx, sy = x, y
            path.moveTo(x, y)
            cmd = "L"
        elif cmd == "L":
            x, y = num(), num()
            path.lineTo(x, y)
        elif cmd == "H":
            x = num()
            path.lineTo(x, y)
        elif cmd == "V":
            y = num()
            path.lineTo(x, y)
        elif cmd == "C":
            c1x, c1y, c2x, c2y, x, y = (num() for _ in range(6))
            path.cubicTo(c1x, c1y, c2x, c2y, x, y)
        elif cmd == "Q":
            cx, cy, x, y = (num() for _ in range(4))
            path.quadTo(cx, cy, x, y)
        elif cmd == "A":
            rx, _ry, _rot, large, sweep, nx, ny = (num() for _ in range(7))
            _arc_to(path, x, y, rx, int(large), int(sweep), nx, ny)
            x, y = nx, ny
        elif cmd == "Z":
            path.closeSubpath()
            x, y = sx, sy
            cmd = None
        else:
            raise ValueError(f"bad path data near token {i}: {d[:40]}")
    return path


def _smooth_closed(pts) -> QPainterPath:
    """Catmull-Rom through the points as cubics (gen-shapes smoothClosed)."""
    path = QPainterPath()
    path.setFillRule(Qt.WindingFill)
    n = len(pts)
    path.moveTo(*pts[0])
    for i in range(n):
        p0, p1, p2, p3 = pts[(i - 1) % n], pts[i], pts[(i + 1) % n], pts[(i + 2) % n]
        path.cubicTo(p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6,
                     p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6, p2[0], p2[1])
    path.closeSubpath()
    return path


def _squircle(half, n, steps=64):
    pts = []
    for i in range(steps):
        a = i / steps * 2 * math.pi
        c, s = math.cos(a), math.sin(a)
        pts.append((50 + half * math.copysign(abs(c) ** (2 / n), c) if c else 50.0,
                    50 + half * math.copysign(abs(s) ** (2 / n), s) if s else 50.0))
    return _smooth_closed(pts)


def _blob(fn, steps=48):
    pts = []
    for i in range(steps):
        a = i / steps * 2 * math.pi
        r = fn(a)
        pts.append((50 + r * math.cos(a), 50 + r * math.sin(a)))
    return _smooth_closed(pts)


